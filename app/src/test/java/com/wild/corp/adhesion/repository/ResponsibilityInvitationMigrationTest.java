package com.wild.corp.adhesion.repository;

import liquibase.integration.spring.SpringLiquibase;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.SingleConnectionDataSource;
import static org.assertj.core.api.Assertions.*;

class ResponsibilityInvitationMigrationTest {
    @Test void preservesParticipantRepliesAndCreatesIndependentUnpublishedResponsibilityInvitations() throws Exception {
        try (var ds = new SingleConnectionDataSource("jdbc:h2:mem:responsibility_invitations;MODE=PostgreSQL", "sa", "", true)) {
            var db = new JdbcTemplate(ds);
            db.execute("CREATE TABLE convocations_equipe (id bigint generated by default as identity primary key, seance_id bigint, adherent_id bigint, adhesion_id bigint NOT NULL, selectionnee boolean, publication timestamp, reponse boolean, date_reponse timestamp, repondu_par bigint, CONSTRAINT uk_convocation_person_session UNIQUE(seance_id,adherent_id))");
            db.execute("INSERT INTO convocations_equipe (seance_id,adherent_id,adhesion_id,selectionnee,reponse,date_reponse) VALUES (20,12,100,true,true,CURRENT_TIMESTAMP)");
            db.execute("CREATE TABLE equipes (id bigint primary key, nom varchar(100))");
            db.execute("INSERT INTO equipes VALUES (10, 'Débutants')");
            db.execute("CREATE TABLE taches_seance (id bigint primary key, nom varchar(100))");
            db.execute("INSERT INTO taches_seance VALUES (3, 'Matériel'), (4, 'Accueil')");
            db.execute("CREATE TABLE responsabilites_seance (seance_id bigint, position integer, tache_id bigint, adherent_id bigint, equipe_id bigint)");
            db.execute("INSERT INTO responsabilites_seance VALUES (20,0,3,12,10), (20,1,4,12,NULL)");
            var migration = new SpringLiquibase(); migration.setDataSource(ds);
            migration.setChangeLog("classpath:db/changelog/v2/changeset-v22.xml");
            migration.afterPropertiesSet(); migration.afterPropertiesSet();
            assertThat(db.queryForObject("SELECT count(*) FROM convocations_equipe", Integer.class)).isEqualTo(3);
            assertThat(db.queryForObject("SELECT reponse FROM convocations_equipe WHERE objet='PARTICIPANT'", Boolean.class)).isTrue();
            assertThat(db.queryForObject("SELECT date_reponse FROM convocations_equipe WHERE objet='PARTICIPANT'", java.sql.Timestamp.class)).isNotNull();
            assertThat(db.queryForList("SELECT objet FROM convocations_equipe WHERE objet <> 'PARTICIPANT'", String.class))
                    .containsExactlyInAnyOrder("RESPONSABILITE:3:10", "RESPONSABILITE:4:0");
            assertThat(db.queryForObject("SELECT responsabilite FROM convocations_equipe WHERE objet='RESPONSABILITE:3:10'", String.class))
                    .isEqualTo("Matériel · Débutants");
            assertThat(db.queryForObject("SELECT count(*) FROM convocations_equipe WHERE objet <> 'PARTICIPANT' AND adhesion_id IS NULL AND publication IS NULL AND reponse IS NULL AND date_reponse IS NULL", Integer.class)).isEqualTo(2);
            assertThatThrownBy(() -> db.execute("INSERT INTO convocations_equipe (seance_id,adherent_id,objet) VALUES (20,12,'RESPONSABILITE:3:10')"))
                    .isInstanceOf(org.springframework.dao.DataIntegrityViolationException.class);
        }
    }
}
